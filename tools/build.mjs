// Rebuild the standalone bundle and loader using Node.js built-ins.
import { writeFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { root, read, sources, literal, transport } from './source_files.mjs';

const write = (path, text) => writeFileSync(resolve(root, path), text, 'utf8');
if (process.argv.includes('--iris')) {
  const directory = 'vendor/Iris/lib';
  const files = readdirSync(resolve(root, directory), { recursive: true })
    .filter(path => path.endsWith('.lua')).map(path => path.replaceAll('\\', '/'))
    .sort((a, b) => a.toLowerCase() < b.toLowerCase() ? -1 : a.toLowerCase() > b.toLowerCase() ? 1 : 0);
  const old = read('vendor/Iris/Bundle.lua');
  const index = old.lastIndexOf("\nlocal root={Name='Iris'}");
  if (index < 0) throw new Error('Iris module loader is missing');
  write('vendor/Iris/Bundle.lua', '-- Generated by tools/build.mjs --iris\n--' +
    literal('\n' + read('vendor/Iris/LICENSE.txt') + '\n') + '\nlocal sources={}\n' +
    files.map(path => `sources["${path}"]=${literal(read(`${directory}/${path}`))}\n`).join('') + old.slice(index));
  console.log('Built vendor/Iris/Bundle.lua');
}
const bundle = '-- Generated by tools/build.mjs. One HTTP request; no module/asset downloads.\nlocal files={}\n' +
  sources.map(path => `files["${path}"]=${literal(read(path))}\n`).join('') +
  `local chunk,message=loadstring(files['main.lua'],'@Legit/main.lua')
assert(type(chunk)=='function','[Legit] Compile failed: '..tostring(message))
return chunk(files)
`;
write('Legit.lua', bundle);
write('loader.lua', '-- Generated by tools/build.mjs; paste this whole file into the executor.\n' + transport() + `
assert(type(loadstring)=='function','Legit needs loadstring support')
local source=download('main.lua')
local chunk,message=loadstring(source,'@Legit/main.lua')
assert(chunk,'Legit main compile failed: '..tostring(message))
return chunk()
`);
console.log(`Built Legit.lua (${Buffer.byteLength(bundle).toLocaleString('en-US')} bytes) and loader.lua`);
