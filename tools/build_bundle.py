"""Build one self-contained file: application, Tokyo, renderers and all PNG data."""
from base64 import b64encode
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sources = ['vendor/Tokyo.lua', 'src/Engine.lua', 'src/GuiDrawing.lua', 'main.lua']
parts = ['-- Generated by tools/build_bundle.py. One HTTP request; no module/asset downloads.\nlocal files={}\n']
for name in sources:
    text = (root / name).read_text(encoding='utf-8')
    assert ']====]' not in text
    parts.append(f'files["{name}"]=[====[{text}]====]\n')
parts.append('''local alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
local digits={}
for i=1,#alphabet do digits[alphabet:sub(i,i)]=i-1 end
local function decode(text)
    local bytes={}
    for i=1,#text,4 do
        local a,b,c,d=text:sub(i,i),text:sub(i+1,i+1),text:sub(i+2,i+2),text:sub(i+3,i+3)
        local value=(digits[a] or 0)*262144+(digits[b] or 0)*4096+(digits[c] or 0)*64+(digits[d] or 0)
        bytes[#bytes+1]=string.char(math.floor(value/65536)%256)
        if c~='=' then bytes[#bytes+1]=string.char(math.floor(value/256)%256) end
        if d~='=' then bytes[#bytes+1]=string.char(value%256) end
    end
    return table.concat(bytes)
end
''')
for asset in sorted((root / 'assets').glob('*.png')):
    parts.append(f'files["assets/{asset.name}"]=decode("{b64encode(asset.read_bytes()).decode("ascii")}")\n')
parts.append('''local chunk,message=loadstring(files['main.lua'],'@Legit/main.lua')
assert(type(chunk)=='function','[Legit] Compile failed: '..tostring(message))
return chunk(files)
''')
output = ''.join(parts)
(root / 'Legit.lua').write_text(output, encoding='utf-8', newline='\n')
print(f'Built Legit.lua: {len(output.encode("utf-8")):,} bytes')
