"""Build one self-contained script using only native Roblox UI and rendering."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sources = ['vendor/Obsidian/Lucide.lua', 'vendor/Obsidian/Library.lua', 'src/ObsidianUI.lua', 'src/Engine.lua', 'src/GuiDrawing.lua', 'src/MeleeAura.lua', 'src/UniversalTools.lua', 'main.lua']
parts = ['-- Generated by tools/build_bundle.py. One HTTP request; no module/asset downloads.\nlocal files={}\n']
for name in sources:
    text = (root / name).read_text(encoding='utf-8')
    equals = '===='
    while ']' + equals + ']' in text:
        equals += '='
    parts.append(f'files["{name}"]=[{equals}[{text}]{equals}]\n')
parts.append('''local chunk,message=loadstring(files['main.lua'],'@Legit/main.lua')
assert(type(chunk)=='function','[Legit] Compile failed: '..tostring(message))
return chunk(files)
''')
output = ''.join(parts)
(root / 'Legit.lua').write_text(output, encoding='utf-8', newline='\n')
print(f'Built Legit.lua: {len(output.encode("utf-8")):,} bytes')
