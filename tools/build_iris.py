"""Package unmodified Iris modules for the executor's loadstring environment."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
lib = root / 'vendor/Iris/lib'
license_text = (root / 'vendor/Iris/LICENSE.txt').read_text(encoding='utf-8')
parts = ['-- Generated by tools/build_iris.py\n--[====[\n' + license_text + '\n]====]\nlocal sources={}\n']
for file in sorted(lib.rglob('*.lua')):
    source = file.read_text(encoding='utf-8')
    equals = '===='
    while ']' + equals + ']' in source:
        equals += '='
    path = file.relative_to(lib).as_posix()
    parts.append(f'sources["{path}"]=[{equals}[{source}]{equals}]\n')
parts.append('''local root={Name='Iris'}
local function nodeAt(path)
    local node=root
    for name in path:gmatch('[^/]+') do
        if not node[name] then node[name]={Name=name,Parent=node} end
        node=node[name]
    end
    return node
end
for path in pairs(sources) do
    local modulePath=path:gsub('%.lua$',''):gsub('/?init$','')
    nodeAt(modulePath).SourcePath=path
end
local cache,loading={},{}
local base=getfenv()
local function localRequire(node)
    assert(type(node)=='table' and node.SourcePath,'Unknown bundled Iris module')
    if cache[node]~=nil then return cache[node] end
    assert(not loading[node],'Circular bundled Iris require: '..node.SourcePath)
    loading[node]=true
    local chunk,message=loadstring(sources[node.SourcePath],'@Legit/vendor/Iris/lib/'..node.SourcePath)
    assert(chunk,message)
    setfenv(chunk,setmetatable({script=node,require=localRequire},{__index=base}))
    local result=chunk()
    assert(result~=nil,'Iris module returned nil: '..node.SourcePath)
    loading[node]=nil; cache[node]=result
    return result
end
return localRequire(root)
''')
(root / 'vendor/Iris/Bundle.lua').write_text(''.join(parts), encoding='utf-8', newline='\n')
print('Built vendor/Iris/Bundle.lua')
