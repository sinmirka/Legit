"""Build an offline bootstrap with exactly the same HTTP transport as main.lua."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
main = (root / 'main.lua').read_text(encoding='utf-8')
start = main.index('-- BEGIN HTTP TRANSPORT')
end = main.index('-- END HTTP TRANSPORT') + len('-- END HTTP TRANSPORT')
loader = '-- Generated by tools/build_loader.py; paste this whole file into the executor.\n'
loader += main[start:end] + '\n'
loader += '''assert(type(loadstring)=='function','Legit needs loadstring support')
local source=download('main.lua')
local chunk,message=loadstring(source,'@Legit/main.lua')
assert(chunk,'Legit main compile failed: '..tostring(message))
return chunk()
'''
(root / 'loader.lua').write_text(loader, encoding='utf-8', newline='\n')
xeno = loader.replace("local source=download('main.lua')", "assert(type(getgenv)=='function','Legit needs getgenv support')\ngetgenv().LegitRenderer='GUI'\nlocal source=download('main.lua')")
(root / 'loader-xeno.lua').write_text(xeno, encoding='utf-8', newline='\n')
